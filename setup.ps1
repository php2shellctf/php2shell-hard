[CmdletBinding()]
param(
    [switch]$NoBrowser,
    [switch]$Recreate,
    [switch]$ReuseSession
)

$ErrorActionPreference = 'Stop'
$challengeDir = $PSScriptRoot
$targetUrl = 'http://127.0.0.1:44158/'
$statusUrl = 'http://127.0.0.1:44159/status.php'
$workerBase = 'https://php2shell-hard-verifier.php2shell.workers.dev'
$managedEnvNames = @(
    'PHP2SHELL_RANKING_URL',
    'PHP2SHELL_KEY_URL',
    'PHP2SHELL_CHECK_URL',
    'PHP2SHELL_SESSION_TOKEN'
)

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    throw 'Docker Desktop was not found in PATH.'
}

function Wait-Http {
    param([string]$Uri, [string]$Label)
    for ($i = 1; $i -le 40; $i++) {
        try {
            $response = Invoke-WebRequest -UseBasicParsing -Uri $Uri -TimeoutSec 3
            if ($response.StatusCode -ge 200 -and $response.StatusCode -lt 500) { return }
        } catch { }
        Start-Sleep -Seconds 1
    }
    throw "Endpoint '$Label' did not become ready: $Uri"
}

function Read-DotEnv {
    param([Parameter(Mandatory)][string]$Path)

    $values = @{}
    if (-not (Test-Path -LiteralPath $Path)) { return $values }
    foreach ($line in Get-Content -LiteralPath $Path) {
        if ($line -match '^\s*([A-Za-z_][A-Za-z0-9_]*)=(.*)$') {
            $values[$matches[1]] = $matches[2]
        }
    }
    return $values
}

function Write-DotEnv {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][hashtable]$Values
    )

    $lines = @(
        '# Generated by setup.ps1; this file is ignored by Git.'
        "PHP2SHELL_RANKING_URL=$($Values['PHP2SHELL_RANKING_URL'])"
        "PHP2SHELL_KEY_URL=$($Values['PHP2SHELL_KEY_URL'])"
        "PHP2SHELL_CHECK_URL=$($Values['PHP2SHELL_CHECK_URL'])"
        "PHP2SHELL_SESSION_TOKEN=$($Values['PHP2SHELL_SESSION_TOKEN'])"
    )
    [System.IO.File]::WriteAllLines($Path, $lines, [System.Text.UTF8Encoding]::new($false))
}

function New-RemoteSession {
    $session = Invoke-RestMethod -Uri "$workerBase/session" -Method Post `
        -ContentType 'application/json' -Body '{}' -TimeoutSec 15
    if ($session.status -ne 'created' -or [string]::IsNullOrWhiteSpace([string]$session.session_id)) {
        throw "Remote verifier did not create a session: $($session | ConvertTo-Json -Compress)"
    }
    return [string]$session.session_id
}

Set-Location -LiteralPath $challengeDir
$envFile = Join-Path $challengeDir '.env'
$envExample = Join-Path $challengeDir '.env.example'
if (-not (Test-Path -LiteralPath $envFile) -and (Test-Path -LiteralPath $envExample)) {
    Copy-Item -LiteralPath $envExample -Destination $envFile
    Write-Host 'Created .env from .env.example.' -ForegroundColor DarkCyan
}
$config = Read-DotEnv -Path $envFile
$config['PHP2SHELL_RANKING_URL'] = "$workerBase/leaderboard"
$config['PHP2SHELL_KEY_URL'] = "$workerBase/key"
$config['PHP2SHELL_CHECK_URL'] = "$workerBase/check"
$hasSession = $config.ContainsKey('PHP2SHELL_SESSION_TOKEN') -and
    -not [string]::IsNullOrWhiteSpace([string]$config['PHP2SHELL_SESSION_TOKEN']) -and
    [string]$config['PHP2SHELL_SESSION_TOKEN'] -ne 'GENERATED_BY_SETUP'
if ($ReuseSession -and $hasSession) {
    Write-Host 'Reusing the existing remote verifier session.' -ForegroundColor DarkCyan
} else {
    Write-Host 'Creating a fresh remote verifier session...' -ForegroundColor DarkCyan
    $config['PHP2SHELL_SESSION_TOKEN'] = New-RemoteSession
}
Write-DotEnv -Path $envFile -Values $config
foreach ($name in $managedEnvNames) {
    Set-Item -Path "Env:$name" -Value ([string]$config[$name])
}
$composeArgs = @('compose', 'up', '-d')
if ($Recreate) { $composeArgs += '--force-recreate' }
& docker @composeArgs
if ($LASTEXITCODE -ne 0) { throw 'docker compose up failed.' }

Wait-Http -Uri $targetUrl -Label 'challenge'
Wait-Http -Uri $statusUrl -Label 'proof status'

Write-Host 'PHP2Shell HARD is ready.' -ForegroundColor Green
Write-Host "Challenge: $targetUrl"
Write-Host "Status:    $statusUrl"
Write-Host 'Remote verifier configured. Run with -ReuseSession only when you intentionally want to keep the existing session.' -ForegroundColor Yellow

if (-not $NoBrowser) { Start-Process $targetUrl }
